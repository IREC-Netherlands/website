		<h1>PENGAKUAN IMAN REFORMED INJILI</h1>

		<h3>ALLAH</h3>
		<p>
			Kami percaya kepada satu-satunya Allah yang hidup dan benar, yang kekal dan keberadaan-Nya
			tergantung pada dirinya sendiri, yang melampaui dan mendahului semua ciptaan; yang dalam
			kekekalan-Nya ada dalam tiga pribadi; Bapa, Putera dan Roh Kudus, yaitu Allah yang Esa; yang
			menciptakan alam semesta dari ketiadaan oleh Firman-Nya yang berkuasa; yang menopang dan
			memerintah segala sesuatu yang telah diciptakan-Nya serta memelihara ketetapan-ketetapan-Nya
			yang kekal.
		</p>

		<h3>ALKITAB</h3>
		<p>
			Kami percaya bahwa Alkitab Perjanjian Lama dan Perjanjian Baru adalah penyataan Allah yang
			sempurna yang diilhamkan Roh Kudus kepada para penulisnya dan karena itu adalah benar tanpa
			salah dalam naskah aslinya. Alkitab menyatakan di dalamnya kesaksian Roh Kudus, dan merupakan
			wibawa tunggal dan mutlak bagi iman dan kehidupan, baik untuk perseorangan, gereja, maupun
			masyarakat. Kami percaya bahwa Alkitab tidak bersalah dalam segala hal yang diajarkannya,
			termasuk hal-hal yang menyangkut sejarah dan ilmu.
		</p>

		<h3>MANUSIA</h3>
		<p>
			Kami percaya bahwa manusia telah diciptakan secara unik menurut rupa Allah, diciptakan dengan
			kekudusan, keadilan dan pengenalan sejati; dan diperintahkan Allah untuk menghayati
			pikiran-pikiran Allah sebagai seorang pemelihara perjanjian yang taat: ia dipercayakan untuk
			memerintah dan mengusahakan ciptaan Allah lainnya untuk kemuliaan Allah. Kami percaya bahwa
			seluruh segi kehidupan harus dihayati di bawah perintah Allah sebagai ungkapan ketaatan kepada
			hukum-hukum Allah.
		</p>

		<h3>DOSA</h3>
		<p>
			Kami percaya bahwa apa yang telah terjadi dalam diri Adam dan juga adalah wakil umat manusia,
			mengakibatkan seluruh umat manusia telah jatuh dalam dosa dan maut; mati secara rohani, patut
			menerima murka adil Allah, tanpa pengharapan dan tanpa pertolongan untuk memperoleh
			keselamatan, baik dari dirinya sendiri atau dari luar dirinya maupun dari dunia ini.
		</p>

		<h3>PERJANJIAN ANUGERAH</h3>
		<p>
			Kami percaya bahwa Allah dalam kekekalan telah membuat perjanjian untuk umat pilihan-Nya,
			dengan Yesus Kristus sebagai Kepala; bahwa melalui ketaatan Yesus Kristus yang sempurna dan
			kematian-Nya sebagai pengganti manusia di kayu salib, Kristus telah memenuhi tuntutan murka
			Allah terhadap umat-Nya. Melalui kuasa kebangkitan Kristus, Allah terus-menerus memanggil dan
			mengumpulkan umat-Nya dari segala zaman dan segala bangsa untuk menjadi suatu imamat yang
			rajani dan bangsa yang kudus bagi kemuliaan-Nya.
		</p>

		<h3>YESUS KRISTUS</h3>
		<p>
			Kami percaya kepada Yesus Kristus, Pribadi kedua Allah Tritunggal, Allah sejati dan manusia
			sejati, satu-satunya Juruselamat manusia; yang telah dikandung oleh Roh Kudus, lahir dari anak
			dara Maria; hidup tanpa dosa, disalibkan mati dan bangkit dari kematian, naik ke surga, duduk
			di sebelah kanan Allah Bapa untuk bersyafaat bagi umat-Nya sebagai Imam Besar, yang berhasil
			dan penuh pengertian; bahwa Dia akan datang kembali dalam tubuh kemuliaan-Nya, secara
			kasatmata dan secara tiba-tiba untuk menghakimi orang yang hidup dan yang mati.
		</p>

		<h3>ROH KUDUS</h3>
		<p>
			Kami percaya kepada Roh Kudus, Pribadi ketiga Allah Tritunggal, Pengilham Ilahi Alkitab, yang
			menginsyafkan manusia akan dosa mereka melalui Firman-Nya, yang melahirbarukan mereka,
			sehingga tumbuh iman dan pertobatan kepada Yesus Kristus untuk keselamatan; Dia memperlengkapi
			orang-orang beriman dengan kuasa untuk menaati hukum-hukum Allah; Dia mengaruniakan kepada
			Gereja Yesus Kristus karunia-karunia untuk pelayanan orang kudus; Dia bersyafaat bagi orang
			beriman dengan keluh kesah yang tak terucapkan untuk dan sampai hari pemuliaan umat Allah.
		</p>

		<h3>GEREJA & MISI</h3>
		<p>
			Kami percaya akan satu Gereja yang kudus dan am, yang terdiri dari seluruh umat pilihan Allah
			dari segala zaman dan yang sebagiannya kini terhisap dalam gereja setempat; gereja setempat
			harus merupakan ungkapan dari sifat Gereja yang kudus dan am tersebut dengan menjaga kemurnian
			ajaran sesuai dengan Alkitab, dengan mendahulukan persatuan berdasarkan kebenaran di dalam
			ikatan kasih antara berbagai gereja setempat dan aliran gereja yang ada, dengan memancarkan
			kemuliaan Allah melalui ibadah, pengajaran Firman Allah, pelaksanaan baptisan dan perjamuan
			kudus, persekutuan, pelaksanaan disiplin dalam kasih, pelayanan dan misi, kami percaya bahwa
			gereja ada di dalam dunia untuk memberitakan Injil Yesus Kristus dan mengungkapkan Ketuhanan
			Kristus lewat perbuatan-perbuatan nyata. Gereja menjalankan misi Yesus Kristus, yaitu
			menegakkan pemerintahan Kerajaan Allah atas dunia ini, baik melalui usaha-usaha penginjilan di
			dunia ini, sampai Kristus datang kembali untuk merampungkan penggenapan Kerajaan-Nya.
		</p>
