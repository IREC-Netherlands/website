		<h1 class="Movements_title">Creed of Reformed Evangelical Movement</h1>
		<h3>The Triune God</h3>
		<p>
			We believe in one living and true God, eternal and self-sufficient in His existence, who
			transcends and precedes all creation. In His eternity, the One God exists in three distinct
			persons: the Father, the Son, and the Holy Spirit. The Father is not begotten by or from
			anyone. The Son is begotten by the Father in eternity. The Holy Spirit proceeds from the
			Father and the Son in eternity. These three Persons are equal in their divinity and one in
			their essence so that the mind, affection, and will of these three Persons are one. In
			connection with His plan of salvation, the Son submits Himself to the Father and the Holy
			Spirit submits Himself to the Father and the Son. This living God is the Creator, Redeemer,
			Sustainer, and Judge. God created the universe out of nothing by His powerful Word, which is
			independent of His creation. He sustains and governs all that He has created and preserves His
			creation. God’s creation is a historical fact. Therefore, God is sovereign over all His
			creation, establishes everything from eternity by His power and will, and preserves His
			eternal decrees. God’s decree is not based on what He sees will happen in the future and
			outside of Himself but solely based on His will. For the sake of expressing His glory, God
			predestined some people and angels to eternal life and predetermined others to eternal
			destruction. God is Spirit, unlimited, indivisible, immutable, omnipotent, omniscient, perfect
			in His decisions, His righteousness, His gentleness, and His mercy. The general revelation of
			God in creation is enough to reveal who God is.
		</p>
		<h3>The Bible</h3>
		<p>
			We believe that the fall of man made the Bible the special revelation of God absolutely
			necessary for man to gain the knowledge of God and His will necessary for his salvation. The
			Bible consists of 39 books of the Old Testament and 27 books of the New Testament and is the
			perfect revelation of God. Although written by men, all the words of the Bible were breathed
			into the writers by the Holy Spirit and are therefore true and without error in the original
			manuscripts in all things taught, including matters concerning history and science. In His
			providence, God has preserved the purity of His Word from age to age, both in duplication and
			translation, so that the Bible continues to speak to all mankind throughout the ages. After
			the canonization of the Bible was complete, God no longer gave new revelation so that God’s
			people are not permitted to add to or take away from what God has already revealed in the
			Bible. The Bible claims to be the Word of God and by the Holy Spirit God’s people are
			convinced of the truth of the Bible as the Word of God. As the Word of God for His people, the
			Bible has authority, is absolutely necessary, sufficient, and clear so that it is useful for
			teaching, for reproof, for correction, and for training people in righteousness. The Bible has
			sole and absolute authority for personal faith and life, the church, and also the testimony of
			God’s people in society until Christ returns.
		</p>
		<h3>Human being</h3>
		<p>
			We believe that the first human being, Adam, was uniquely created as body and spirit/soul in
			the image and likeness of God and was created with true holiness, righteousness, and
			knowledge. The creation of human beings, as male and female, is a historical fact. As a
			creature in relationship to God, Adam was created to live out the thoughts of God and to obey
			God. As the representative of humanity, Adam’s obedience was tested through a covenant of
			works in which eternal life was promised to Adam and his descendants on the basis of perfect
			and continuing personal obedience. Although created as God’s representative to rule over and
			subdue all of God’s other creations, humans are not there to exploit nature but are entrusted
			to work and keep God’s creation for God’s glory. As a faithful covenant keeper, God demands
			that all aspects of human life be lived under God’s command as an expression of obedience to
			God’s laws.
		</p>
		<h3>Sin</h3>
		<p>
			We believe that Adam failed in his personal obedience to God by breaking God’s command. Adam’s
			fall resulted in the image of God being corrupted, so that all aspects of human life were
			tainted by sin and humans experienced alienation from God, from themselves, and from the rest
			of creation. As the representative of humanity, Adam’s fall resulted in all humanity falling
			into sin and death spreading to all people, resulting in the entire creation being cursed and
			subjected to futility. Spiritually dead and separated from the Triune God, humans received
			God’s just wrath, without hope and without help for salvation, either from themselves or from
			creation.
		</p>
		<h3>Covenant of grace</h3>
		<p>
			We believe that God in eternity made a covenant for His chosen people, with Jesus Christ as
			Mediator. As the second and last Adam, Jesus Christ gave His perfect personal obedience to
			God’s law (active obedience) and His suffering even to death on the cross (passive obedience)
			and thus fulfilled the covenant of works that Adam failed to fulfill. Because of Christ’s
			perfect obedience, God no longer demands obedience as the basis of our salvation, but now
			offers a covenant of grace to those, both old and new covenant people, who believe in the
			perfect obedience of Christ. Through the power of Christ’s resurrection, God continues to call
			and gather His people from all ages and nations to be a royal priesthood and a holy nation for
			His glory.
		</p>
		<h3>Jesus Christ</h3>
		<p>
			We believe in Jesus Christ, the second Person of the Trinity, true God and true man, the only
			Savior of mankind who fulfilled God the Father’s plan of salvation for God’s chosen people.
			Although equal to God the Father, Christ emptied Himself by taking on a human nature in His
			incarnation. In His incarnation, He is fully God and fully man, both natures unconfused,
			unchangeable, undivided, and inseparable and both united in one Person. As a man, Christ had a
			human mind and will. He was conceived by the Holy Spirit and born of the virgin Mary, became
			like us, but without sin, was crucified, died and rose from the dead, received a glorified
			body of flesh and blood, ascended into heaven and is seated at the right hand of God the
			Father in His glorified body, and will come again in His glorified body. He came, died on the
			cross, and was resurrected for the sake of God’s chosen people. His sacrifice was a sacrifice
			that atones for our sins (atonement), that justifies us before God (expiation), that
			reconciles us to God (propitiation), and that satisfies God’s justice towards us
			(satisfaction). Through His perfect obedience, our sins were imputed to Him and His
			righteousness was imputed to us (double imputation). As the only Mediator between God and
			humans, Christ simultaneously fulfills threefold office that is important for our salvation:
			Prophet, Priest, and King. As a Prophet, Christ announced God’s will and plan to God’s people.
			As Priest, Christ sacrificed Himself for God’s people and interceded for us with
			understanding. As King, Christ rules God’s people with His Word and Spirit. He is the Good
			Shepherd who gives the abundance of His life through His self-sacrifice for His sheep so that
			we can enjoy that abundance in a sacrificial life like Him. Christ will return in His
			glorified body, visibly and suddenly, to judge the living and the dead.
		</p>
		<h3>Holy Spirit</h3>
		<p>
			We believe in the Holy Spirit, the third Person of the Trinity, the Divine Inspirer of the
			Bible, who comes to apply the salvation accomplished by the Son of God to the elect of God.
			The Holy Spirit comes not to bear witness to Himself, but to exalt Christ. He convicts human
			beings of their sin through His Word, regenerates them by giving them faith that unites them
			to Christ so that they receive justification and sanctification, and abides forever in them to
			comfort them and grow their faith. He equips believers with power to obey God’s laws. He
			bestows gifts for the service of the saints for the good of the Church of Christ; He
			intercedes for believers with groanings too deep for words for and until the day of the
			glorification of the people of God.
		</p>
		<h3>Moral responsibility and good works</h3>
		<p>
			We believe that although God has ordained all things, including the salvation of human, God’s
			decree does not make God the author of sin and eliminate human free will. Moreover, humans are
			responsible for all their thoughts and deeds. And although salvation is based on God’s grace
			alone received through faith in Christ alone, not because of good works, yet salvation is
			inseparable from good works, hope, and love. This saving faith will bring forth many good
			works in the children of God, namely, good works that are in accordance with God’s holiness,
			pleasing to God, commanded by God in His Word, and for the glory of God.
		</p>
		<h3>Church</h3>
		<p>
			We believe in one holy and catholic Church, consisting of all God’s elect of all times,
			revealed through the once-for-all event of Pentecost, and part of which is now absorbed in the
			local church, outside of which there is no possibility of ordinary salvation. The local church
			must be an expression of the character of this holy and catholic Church by maintaining the
			purity of doctrine according to the Bible, by reflecting the glory of God through worship,
			teaching the Word of God, administering baptism and the Lord’s Supper, fellowship, exercising
			discipline in love, service and mission, and by prioritizing unity among the various local
			churches and denominations based on the truth in the bond of love.
		</p>
		<h3>Sacrament</h3>
		<p>
			We acknowledge the two sacraments ordained by God for the Church, holy baptism and holy
			communion. The sacrament is not the gift, but a seal of the covenant of God’s grace to human,
			a visible sign of the invisible promise. The sacrament of baptism, performed once in a
			lifetime, is the sign and seal of believers’ union with Christ, of the justification and
			forgiveness of their sins, and of their new birth. Through the sacrament of baptism, believers
			are incorporated into the local church. The sacrament of Holy Communion, performed repeatedly,
			in which believers spiritually receive the body and blood of Christ, is a sign and seal of
			their sanctification and of all the spiritual benefits of Christ’s sacrifice that they have
			received. Through the sacrament of Holy Communion, believers who have been united into the
			body of Christ are constantly reminded of Christ’s sacrifice. The sacrament of Baptism is
			administered to those who profess to believe and their children. The sacrament of Holy
			Communion is performed for those who have been able to judge themselves truly. Although the
			sacrament is not a gift, when accompanied by the preaching of the Word of God and accepted
			with faith, the sacrament has an absolutely necessary part in the life of a child of God.
		</p>
		<h3>Mission</h3>
		<p>
			We believe that the Church is in the world to witness the lordship of Christ. Until Christ
			returns to complete the fulfillment of His Kingdom, the Church carries out the mission of
			Jesus Christ to make disciples of all nations by preaching the gospel to all corners of the
			earth, teaching them, and baptizing them in the name of the Father, the Son, and the Holy
			Spirit. The Church is also called to establish the reign of God’s Kingdom over this world and
			to proclaim God’s redemptive shalom to all creation by advocating for God’s righteousness and
			holiness for all people, expressing social and environmental concerns, and through other
			concrete actions.
		</p>
		<h3>End times</h3>
		<p>
			We believe and look forward to the new heavens and new earth, the holy city of God that will
			descend from heaven to earth, through the visible second coming of Christ in power and glory.
			When He comes, He will resurrect and judge all people. Those who believe will be resurrected
			and given glorified bodies, publicly acknowledged and praised by God, completely and forever
			freed from all sin and toil, filled with unspeakable joy, joined and communed with the saints
			and angels, made like Christ, and fully enjoying God in the resurrection body forever and
			ever. Until Christ comes again, we submit ourselves to the reign of Christ as the Head of the
			Church and our hope in this world rests on the fact of the presence of the Kingdom of God
			through the first coming of Christ and the completion of His work so that the world to come
			has been put under His feet and secured to His people.
		</p>
